process.removeAllListeners("warning");
const UI = "/home/claude/work/apk/assets/ui/";
global.Forge = require(UI + "core.js");
const G = require(UI + "guide-model.js");
const B = require(UI + "builder-model.js");
const fs = require("fs");
const { open } = require("./node_db");
(async () => {
  const { schema, query } = open();
  const [cardId, kind, out] = [Number(process.argv[2]), process.argv[3], process.argv[4]];
  const p = await Forge.loadTemplate(query, schema, cardId, Forge.SLOT_FLOOR);
  const existing = await query({ table: "card_awakening_routes", filters: { card_id: cardId }, limit: 100 });
  const donor = await query({ table: "card_awakening_routes", filters: { card_id: 1003211 }, limit: 100 });
  const medals = {}; for (const r of donor) if (r.type === "CardAwakeningRoute::Optimal") medals[r.optimal_awakening_step] = r.card_awakening_set_id;
  B.setupAwaken(p, schema, { kind, existingRoutes: existing, medals, medalName: "SS3 Goku" });
  await G.allocateId(p, query, []);
  console.log("target", p.targetId, "groups passive:", B.stageGroups(p, "passive").map((g) => g.key + "=" + g.setId).join(" "), "leader:", B.stageGroups(p, "leader").map((g) => g.key + "=" + g.setId).join(" "));
  const last = B.stageGroups(p, "passive").slice(-1)[0].key;
  B.ensureStageEditable(p, "passive", last);
  const view = B.stageView(p, "passive", last);
  B.addPassiveAbility(view, "atkdef", { atk: 222, def: 222 });
  B.addPassiveAbility(view, "crit", { amount: 77 });
  const lg = B.stageGroups(p, "leader").slice(-1)[0].key;
  B.ensureStageEditable(p, "leader", lg);
  B.buildLeader(B.stageView(p, "leader", lg), schema, [{ who: "all", ki: 4, hp: 200, atk: 200, def: 200 }], { names: { category: () => "" } });
  B.createSuper(p, schema, { style: "Normal", name: "EZA Blast", lvStart: 14, profiles: [], effects: [{ key: "atk", values: { amount: 50 } }] });
  const check = Forge.validate(p);
  console.log("errors", check.errors);
  fs.writeFileSync(out, Forge.sql(p));
  console.log("tables", Object.entries(Forge.materialize(p)).map(([t, r]) => t + ":" + r.length).join(" "));
})().catch((e) => { console.error(e.stack || e); process.exit(1); });
